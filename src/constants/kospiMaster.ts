// 코스피 우선 통합 리스트
export const ALL_KRX_MASTER_STOCKS: MasterStock[] = [
  ...KOSPI_STOCKS,
  ...KOSDAQ_STOCKS
];

// 코스피 1순위 최우선 검색 알고리즘
export function searchKrMasterStocks(query: string, maxResults = 30): MasterStock[] {
  if (!query || !query.trim()) return [];

  const rawQuery = query.trim();
  const lowerQuery = rawQuery.toLowerCase();
  const isChosungQuery = /^[ㄱ-ㅎ]+$/.test(rawQuery);
  const isNumericCode = /^\d{1,6}$/.test(rawQuery);

  const matched: Array<{ stock: MasterStock; score: number }> = [];

  for (const stock of ALL_KRX_MASTER_STOCKS) {
    let score = 0;
    const nameLower = stock.name.toLowerCase();
    const sym = stock.symbol;
    const engLower = (stock.engName || '').toLowerCase();
    const initials = stock.initials || '';

    // 코스피(KOSPI) 종목 가산점 (+5000점) -> 코스피가 무조건 코스닥보다 1순위 상단에 노출
    const kospiBonus = stock.market === 'KOSPI' ? 5000 : 0;

    if (sym === rawQuery) {
      score = 10000 + kospiBonus; // 종목코드 완벽 일치
    } else if (nameLower === lowerQuery) {
      score = 9000 + kospiBonus; // 종목명 완벽 일치
    } else if (sym.startsWith(rawQuery)) {
      score = 8000 + kospiBonus + (100 - sym.length); // 종목코드 접두사 일치
    } else if (nameLower.startsWith(lowerQuery)) {
      score = 7000 + kospiBonus + (100 - nameLower.length); // 종목명 접두사 일치
    } else if (nameLower.includes(lowerQuery)) {
      score = 6000 + kospiBonus; // 종목명 포함
    } else if (isChosungQuery && initials.includes(rawQuery)) {
      score = 5000 + kospiBonus + (initials.startsWith(rawQuery) ? 500 : 0); // 초성 일치 (예: 'ㅅㅅㅈㅈ' -> 삼성전자)
    } else if (engLower.includes(lowerQuery)) {
      score = 4000 + kospiBonus; // 영문명 포함
    } else if (isNumericCode && sym.includes(rawQuery)) {
      score = 3000 + kospiBonus; // 숫자 코드 포함
    }

    if (score > 0) {
      matched.push({ stock, score });
    }
  }

  // 높은 점수 순(KOSPI 최우선)으로 정렬
  matched.sort((a, b) => b.score - a.score);

  return matched.slice(0, maxResults).map(m => m.stock);
}
